import { _electron as electron, expect } from '@playwright/test';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
const root=await mkdtemp(join(tmpdir(),'optic-extensions-smoke-'));
let app;
const env={...process.env,WORKBENCH_KUBECONFIG:join(root,'absent')};delete env.ELECTRON_RUN_AS_NODE;delete env.ELECTRON_RENDERER_URL;
const launch=async()=>{app=await electron.launch({args:['.',`--user-data-dir=${join(root,'profile')}`],env});const page=await app.firstWindow();await page.getByTitle('Extensions',{exact:true}).click();return page;};
const api=async(page,channel,input)=>{const result=await page.evaluate(({channel,input})=>window.desktop.request(channel,input),{channel,input});if(!result.ok)throw Error(result.error.message);return result.data;};
const install=async(page,path)=>{await app.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]});},path);const review=await api(page,'extensions:pick',{kind:'folder'});return api(page,'extensions:install',{token:review.token});};
try {
 let page=await launch();await mkdir('artifacts/extensions',{recursive:true});
 await page.screenshot({path:'artifacts/extensions/01-empty.png'});
 const example=resolve('examples/extensions/context-summary');
 await app.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]});},example);
 await page.getByRole('button',{name:'Install from folder',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Review extension'})).toContainText('selected cluster');
 await page.getByRole('dialog',{name:'Review extension'}).getByRole('button',{name:'Install extension',exact:true}).click();
 await page.getByRole('button',{name:'Enable',exact:true}).click();
 await expect(page.locator('.extension-state')).toHaveText('running',{timeout:15000});
 await page.getByRole('button',{name:'Show context summary'}).click();
 await expect(page.getByRole('region',{name:'Extension result'})).toContainText('No cluster selected');
 await page.screenshot({path:'artifacts/extensions/02-running.png'});
 // An isolated extension cannot reach the desktop bridge or Node globals.
 const probe=join(root,'probe');await mkdir(probe);
 const commands=[{id:'probe',title:'Check sandbox'},{id:'hang',title:'Hang'},{id:'invalid',title:'Invalid output'}];
 await writeFile(join(probe,'optic-extension.json'),JSON.stringify({apiVersion:1,id:'test.sandbox',name:'Sandbox probe',version:'1.0.0',description:'Test',permissions:[],commands}));
 await writeFile(join(probe,'extension.js'),`optic.registerCommand('probe', async context => { let blocked=false; try { await fetch('https://example.com'); } catch { blocked=true; } return {title:'Sandbox',text:JSON.stringify({node:typeof process,require:typeof require,bridge:typeof window.desktop,webrtc:typeof RTCPeerConnection,context,blocked})}; }); optic.registerCommand('hang',()=>{while(true){}}); optic.registerCommand('invalid',()=>({title:'Bad',html:'<b>unsafe</b>'}));`);
 await install(page,probe);await api(page,'extensions:enable',{id:'test.sandbox',enabled:true});
 const result=await api(page,'extensions:run',{id:'test.sandbox',command:'probe',namespace:'private'});
 assert.deepEqual(JSON.parse(result.text),{node:'undefined',require:'undefined',bridge:'undefined',webrtc:'undefined',context:{},blocked:true});
 const hung=api(page,'extensions:run',{id:'test.sandbox',command:'hang'}).catch(e=>e.message);
 const start=Date.now();await api(page,'extensions:list');assert(Date.now()-start<1500);
 assert.match(await hung,/5-second/);
 await api(page,'extensions:enable',{id:'test.sandbox',enabled:true});
 await assert.rejects(()=>api(page,'extensions:run',{id:'test.sandbox',command:'invalid'}),/invalid data/);
 await api(page,'extensions:remove',{id:'test.sandbox'});
 await page.getByRole('switch',{name:'Safe Mode'}).check();
 await expect(page.locator('.extension-state')).toHaveText('disabled');
 await app.close();page=await launch();
 await expect(page.getByRole('switch',{name:'Safe Mode'})).toBeChecked();
 await page.getByRole('switch',{name:'Safe Mode'}).uncheck();
 await expect(page.locator('.extension-state')).toHaveText('running',{timeout:15000});
 await page.getByRole('button',{name:'Uninstall',exact:true}).click();
 await page.getByRole('button',{name:'Uninstall extension',exact:true}).click();
 await expect(page.locator('.extensions-empty')).toBeVisible();
 console.log('PASS: extension review/install/enable/command, sandbox and network isolation, deadlines, invalid output, persisted Safe Mode, restart and uninstall.');
}finally{await app?.close();await rm(root,{recursive:true,force:true});}
